// Package transpile translates Temari's machine-generated src/rounds_gen.rs
// into Go for amdl's internal/fairplay package.
//
// It accepts only the Rust subset that file uses and fails on anything else,
// so an upstream change that needs a new construct stops the translation
// instead of producing code that means something different. Integer
// arithmetic keeps Rust's release-build wrapping semantics; all-constant
// subexpressions are folded here because Go rejects constant overflow.
//
// The output is not line for line. Function-level u32 locals get a new Go
// name on every assignment, each u32 expression is rewritten into a smaller
// equivalent (simplify.go folds upstream's mixed boolean-arithmetic
// obfuscation, which LLVM folds for Temari and the Go compiler does not), and
// locals nothing reads any more are dropped. Equivalence rests on exact
// identities checked by simplify_test.go and on the byte-for-byte comparison
// with Temari in tools/temaridiff.
package transpile

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// handPorted pins the rounds_gen.rs helpers that are not translated because
// their Rust bodies use unsafe and debug assertions: internal/fairplay/rounds.go
// ports the ones the rounds call (set_byte is unused). When an upstream release
// changes one, File fails with the new digest and the Go side has to be
// reviewed against the new Rust before the pin moves.
var handPorted = map[string]string{
	"t4":       "a5c62e485a11294f25f46ef028acd2ea60db31bfc7a6b527048234336fb23014",
	"ctxb":     "8432c0b23947ce44c7d8622915d4b0a9994a693688cefba821eb6bee29cb6436",
	"set_byte": "d43194af13874ae4a3071ee8328a149b398324cafaa09c95eff4c71ff6c3868f",
}

// handWritten names the package-level identifiers internal/fairplay declares
// outside the generated file, which generated locals must not shadow.
var handWritten = []string{
	"Template", "ParseTemplate", "ctxTable", "ctxSize", "ctxWords", "stateSize", "r1Entry", "stSlots",
	"parseRegister", "decodeBase64", "reconstructBlock",
}

// File returns gofmt-formatted Go source for package fairplay translated from
// src, the contents of Temari's src/rounds_gen.rs at the given version.
func File(src []byte, version string) ([]byte, error) {
	return generate(src, version, handPorted)
}

func generate(src []byte, version string, handPorted map[string]string) ([]byte, error) {
	items, err := parseFile(string(src), handPorted)
	if err != nil {
		return nil, fmt.Errorf("parse rounds_gen.rs: %w", err)
	}
	e := &emitter{
		aliases:  map[string]*typeExpr{},
		structs:  map[string]*structItem{},
		funcs:    map[string]signature{},
		tuples:   map[string]*gtype{},
		reserved: map[string]bool{},
	}
	for _, k := range goKeywords {
		e.reserved[k] = true
	}
	for _, n := range handWritten {
		e.reserved[n] = true
	}
	seenHand := map[string]bool{}
	var changed []string
	topLevel := map[string]bool{}
	define := func(name string) error {
		if topLevel[name] || e.reserved[name] {
			return fmt.Errorf("package-level name %s is defined twice", name)
		}
		topLevel[name] = true
		return nil
	}
	for _, it := range items {
		var name string
		switch it := it.(type) {
		case *typeItem:
			e.aliases[it.name] = it.typ
			name = goName(it.name)
		case *structItem:
			e.structs[it.name] = it
			name = goName(it.name)
		case *constItem:
			name = goName(it.name)
		case *fnItem:
			e.funcs[it.name] = signature{params: it.params, ret: it.ret}
			name = fnName(it.name)
		}
		if err := define(name); err != nil {
			return nil, err
		}
		if it, ok := it.(*fnItem); ok {
			if want, ok := handPorted[it.name]; ok {
				seenHand[it.name] = true
				if it.digest != want {
					changed = append(changed, fmt.Sprintf("%s (digest %s, pinned %q)", it.name, it.digest, want))
				}
			}
		}
	}
	for n := range topLevel {
		e.reserved[n] = true
	}
	if len(changed) > 0 {
		return nil, fmt.Errorf("hand-ported fns changed upstream: %s; review the Go port, then update handPorted", strings.Join(changed, ", "))
	}
	for name := range handPorted {
		if !seenHand[name] {
			return nil, fmt.Errorf("hand-ported fn %s no longer exists upstream", name)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/temaridiff/cmd/transpile from Temari %s src/rounds_gen.rs; DO NOT EDIT.\n\n", version)
	b.WriteString("// Translated from Temari, Copyright (c) 2025 Temari contributors, MIT License; see doc.go.\n\n")
	b.WriteString("package fairplay\n\n")
	writeComments := func(cs []string) {
		for _, c := range cs {
			b.WriteString("//" + c + "\n")
		}
	}
	for _, it := range items {
		switch it := it.(type) {
		case *constItem:
			writeComments(it.comments)
			fmt.Fprintf(&b, "const %s = %s\n\n", goName(it.name), it.val.text)
		case *typeItem:
			t, err := e.typeOf(it.typ, "")
			if err != nil {
				return nil, fmt.Errorf("type %s: %w", it.name, err)
			}
			writeComments(it.comments)
			fmt.Fprintf(&b, "type %s %s\n\n", goName(it.name), e.goTypeUnnamed(t))
		case *structItem:
			writeComments(it.comments)
			fmt.Fprintf(&b, "type %s struct {\n", goName(it.name))
			for _, f := range it.fields {
				t, err := e.typeOf(f.typ, "")
				if err != nil {
					return nil, fmt.Errorf("struct %s field %s: %w", it.name, f.name, err)
				}
				writeComments(f.comments)
				fmt.Fprintf(&b, "%s %s\n", f.name, e.goType(t))
			}
			b.WriteString("}\n\n")
		case *fnItem:
			if _, ok := handPorted[it.name]; ok {
				continue
			}
			if err := e.fn(it); err != nil {
				return nil, err
			}
			writeComments(it.comments)
			b.WriteString(strings.Join(e.lines, "\n") + "\n\n")
		}
	}
	var names []string
	for n := range e.tuples {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "type %s struct {\n", n)
		for i, el := range e.tuples[n].elems {
			fmt.Fprintf(&b, "f%d %s\n", i, e.goType(el))
		}
		b.WriteString("}\n\n")
	}
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gofmt generated code: %w", err)
	}
	return out, nil
}

func (e *emitter) goTypeUnnamed(t *gtype) string {
	cp := *t
	cp.name = ""
	return e.goType(&cp)
}
