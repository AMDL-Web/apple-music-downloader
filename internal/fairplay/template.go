const (
	ctxSize = 0x8000
	// stateSize is the minimum decoded length of the state field. Slot values
	// sit at stateSize-offset, counted back from this boundary.
	stateSize = 0x2000
)

type ctxTable [ctxSize]byte

type r1Entry struct{ rdx, rcx, rax, r9, rbp uint32 }

// Template is a parsed white-box decryption template for one content key. It
// is never modified after ParseTemplate returns.
type Template struct {
	ctx    ctxTable
	stInit state
	r1     r1Entry
}

