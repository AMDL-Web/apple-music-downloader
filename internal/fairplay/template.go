// ParseTemplate parses one wrapper-lite /key response body (the data object:
// ctx, state, rcx, rax, rdx, r9, rbp) into an immutable template. As in
// Temari, ctx and state are required and a missing register reads as zero.
func ParseTemplate(body []byte) (*Template, error) {
	var raw struct {
		Ctx   *string `json:"ctx"`
		State *string `json:"state"`
		Rcx   *string `json:"rcx"`
		Rax   *string `json:"rax"`
		Rdx   *string `json:"rdx"`
		R9    *string `json:"r9"`
		Rbp   *string `json:"rbp"`
	}
	if err := json.Unmarshal(body, &raw); err != nil {
		return nil, fmt.Errorf("parse key template: %w", err)
	}
	if raw.Ctx == nil {
		return nil, errors.New("key template has no ctx field")
	}
	if raw.State == nil {
		return nil, errors.New("key template has no state field")
	}
	ctx, err := decodeBase64(*raw.Ctx)
	if err != nil {
		return nil, fmt.Errorf("decode key template ctx: %w", err)
	}
	if len(ctx) < ctxSize {
		return nil, fmt.Errorf("key template ctx is %d bytes, want at least %d", len(ctx), ctxSize)
	}
	st, err := decodeBase64(*raw.State)
	if err != nil {
		return nil, fmt.Errorf("decode key template state: %w", err)
	}
	if len(st) < stateSize {
		return nil, fmt.Errorf("key template state is %d bytes, want at least %d", len(st), stateSize)
	}

	t := &Template{}
	copy(t.ctx[:], ctx)
	for _, off := range stSlots {
		if int(off) >= stSize {
			continue
		}
		pos := stateSize - int(off)
		t.stInit[off] = binary.LittleEndian.Uint32(st[pos : pos+4])
	}
	for _, r := range []struct {
		name string
		val  *string
		dst  *uint32
	}{
		{"rcx", raw.Rcx, &t.r1.rcx},
		{"rax", raw.Rax, &t.r1.rax},
		{"rdx", raw.Rdx, &t.r1.rdx},
		{"r9", raw.R9, &t.r1.r9},
		{"rbp", raw.Rbp, &t.r1.rbp},
	} {
		if r.val == nil {
			continue
		}
		v, err := parseRegister(*r.val)
		if err != nil {
			return nil, fmt.Errorf("key template %s: %w", r.name, err)
		}
		*r.dst = v
	}
	return t, nil
}

// parseRegister reads a hex register value. r9 and rbp arrive as 64-bit
// pointers; only their low 32 bits feed the rounds.
func parseRegister(s string) (uint32, error) {
	s = strings.TrimPrefix(strings.TrimSpace(s), "0x")
	v, err := strconv.ParseUint(s, 16, 64)
	if err != nil {
		return 0, err
	}
	return uint32(v), nil
}

// decodeBase64 accepts standard base64 with or without padding, as Temari's
// decoder does.
func decodeBase64(s string) ([]byte, error) {
	return base64.RawStdEncoding.DecodeString(strings.TrimRight(s, "="))
}
